export function getProductById(id: string): Product | undefined {
  return italianProducts.find(p => p.id === id);
}

export function searchProducts(
  query: string,
  filter: 'all' | 'sale' | 'bio' | 'local' | ('sale' | 'bio' | 'local')[] | Set<string> = 'all',
  category?: ProductCategory,
  sort: 'suggested' | 'price-asc' | 'price-desc' | 'name-asc' = 'suggested'
): Product[] {
  let list = [...italianProducts];

  // Query filter
  if (query.trim()) {
    const q = query.toLowerCase().trim();
    list = list.filter(p =>
      p.name.toLowerCase().includes(q) ||
      p.brand.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q)
    );
  }

  // Type filters (supports multiple filters simultaneously)
  if (Array.isArray(filter) || filter instanceof Set) {
    const filterSet = new Set(filter);
    if (filterSet.has('sale')) {
      list = list.filter(p => p.isOnSale);
    }
    if (filterSet.has('bio')) {
      list = list.filter(p => p.isBio);
    }
    if (filterSet.has('local')) {
      list = list.filter(p => p.isLocal);
    }
  } else {
    if (filter === 'sale') {
      list = list.filter(p => p.isOnSale);
    } else if (filter === 'bio') {
      list = list.filter(p => p.isBio);
    } else if (filter === 'local') {
      list = list.filter(p => p.isLocal);
    }
  }

  // Category filter
  if (category) {
    list = list.filter(p => p.category === category);
  }

  // Sorting
  list.sort((a, b) => {
    if (sort === 'price-asc') return a.price - b.price;
    if (sort === 'price-desc') return b.price - a.price;
    if (sort === 'name-asc') return a.name.localeCompare(b.name);
    // Default: suggested / popularity
    return b.popularity - a.popularity;
  });

  return list;
}

